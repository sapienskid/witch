var TagSuggest = class extends import_obsidian10.AbstractInputSuggest {
  constructor(app, inputEl, getTags) {
    super(app, inputEl);
    __publicField(this, "getTags", getTags);
    this.limit = 20;
  }
  getSuggestions(query) {
    const tags = this.getTags();
    const q = query.toLowerCase().trim();
    if (!q) {
      return tags.slice(0, 20);
    }
    return tags.filter((tag) => tag.toLowerCase().includes(q)).slice(0, 20);
  }
  renderSuggestion(value, el) {
    el.setText(value);
  }
};
function existingTagNames(app) {
  const all = app.metadataCache.getTags();
  return Object.keys(all).map((key) => key.replace(/^#/, "")).filter((name) => name.length > 0).sort((a, b) => a.localeCompare(b));
}
function createTagSelector(container, app, options) {
  let selected = [...options.tags];
  const root = container.createDiv({ cls: "witch-tag-selector" });
  const chips = root.createDiv({ cls: "witch-tag-chips" });
  const input = root.createEl("input", { type: "text", placeholder: "Select existing tags\u2026", cls: "witch-search" });
  input.setAttr("aria-label", "Select existing tags");
  const renderChips = () => {
    chips.empty();
    for (const tag of selected) {
      const chip = chips.createSpan({ cls: "witch-tag-chip", text: tag });
      const remove = chip.createEl("button", { cls: "witch-tag-remove", attr: { "aria-label": `Remove ${tag}` } });
      remove.setText("\xD7");
      remove.addEventListener("click", () => {
        selected = selected.filter((item) => item !== tag);
        options.onChange(selected);
        renderChips();
      });
    }
  };
  const addTag = (value) => {
    const tag = value.trim();
    if (!tag || selected.includes(tag)) {
      return;
    }
    selected = [...selected, tag];
    options.onChange(selected);
    input.value = "";
    renderChips();
  };
  const suggest = new TagSuggest(app, input, options.availableTags);
  suggest.onSelect((value) => addTag(value));
  input.addEventListener("keydown", (event) => {
    if (event.key === "Enter") {
      const value = input.value.trim();
      if (value && options.availableTags().includes(value)) {
        event.preventDefault();
        addTag(value);
      }
    }
  });
  renderChips();
}

